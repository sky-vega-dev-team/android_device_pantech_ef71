package org.lineageos.settings.ef71.memory;

import android.os.Bundle;

import com.android.settingslib.collapsingtoolbar.CollapsingToolbarBaseActivity;
import com.android.settingslib.collapsingtoolbar.R;

public class MemorySettingsActivity extends CollapsingToolbarBaseActivity {

    private static final String TAG_MEMORY = "memory";

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);

        getFragmentManager().beginTransaction().replace(R.id.content_frame,
                new MemorySettingsFragment(), TAG_MEMORY).commit();
    }
}
